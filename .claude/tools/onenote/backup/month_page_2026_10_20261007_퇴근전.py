def shot_rows(shots=None):
    shots = SHOTS1 if shots is None else shots
    rows = [[cell([oe("대상", bold=True)], "#F2F2F2"), cell([oe("날짜", bold=True)], "#F2F2F2"), cell([oe("화면", bold=True)], "#F2F2F2")]]
    for target, day, fname, title, cap in shots:
        path = fname if os.path.isabs(fname) else os.path.join(SHOT_DIR, fname)
        rows.append([cell([oe(x) for x in target.split("\n")], "#F2F2F2"), cell([oe(day)]),
                     cell([image_path_oe(path, SHOT_W), oe(title, bold=True), oe(cap)])])
    return oe_table(table([95.0, 48.0, 915.0], rows))


