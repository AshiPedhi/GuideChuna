def shot_table(shots, cols=2):
    rows, buf = [], []
    for fname, title, cap in shots:
        buf.append(cell([image_oe(fname), oe(title, bold=True), oe(cap)]))
        if len(buf) == cols:
            rows.append(buf); buf = []
    if buf:
        rows.append(buf + [cell([oe("")])] * (cols - len(buf)))
    return oe_table(table([529.0] * cols, rows))

